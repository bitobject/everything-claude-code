#!/usr/bin/env bash
# Shared helpers for the plugin's hooks. Hooks read one JSON object on stdin and must never
# fail the user's action because of their own bugs: on an internal error they exit 0 silently.

# json_get <jq-path> : read a field from $HOOK_INPUT (jq if present, python3 otherwise).
json_get() {
	if command -v jq >/dev/null 2>&1; then
		jq -r "$1 // empty" <<<"$HOOK_INPUT" 2>/dev/null
	else
		python3 -I -c '
import json, sys
d = json.loads(sys.stdin.read() or "{}")
for k in sys.argv[1].lstrip(".").split("."):
    d = d.get(k) if isinstance(d, dict) else None
print("" if d is None else (str(d).lower() if isinstance(d, bool) else d))
' "$1" <<<"$HOOK_INPUT" 2>/dev/null
	fi
}

# json_string <text> : print text as a JSON string literal.
json_string() {
	if command -v jq >/dev/null 2>&1; then
		jq -Rs . <<<"$1"
	else
		python3 -I -c 'import json, sys; print(json.dumps(sys.stdin.read()))' <<<"$1"
	fi
}

# emit_context <event> <text> : add text to Claude's context after a tool call (non-blocking).
emit_context() {
	printf '{"hookSpecificOutput":{"hookEventName":"%s","additionalContext":%s}}\n' "$1" "$(json_string "$2")"
}

# emit_deny <reason> : deny a PreToolUse call with a reason Claude sees.
emit_deny() {
	printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":%s}}\n' "$(json_string "$1")"
}

# is_generated <file> : true when the file carries a generator header.
#   Go:    "// Code generated ... DO NOT EDIT."  (https://go.dev/s/generatedcode)
#   TS/JS: openapi-typescript's "auto-generated by" / "Do not make direct changes", or "@generated".
is_generated() {
	[[ -f "$1" ]] || return 1
	head -n 30 -- "$1" 2>/dev/null | grep -Eq '^// Code generated .* DO NOT EDIT\.$|auto-generated by |[Dd]o not make direct changes|@generated'
}

# find_up <start-dir> <file-name> : print the nearest ancestor directory containing file-name.
find_up() {
	local dir="$1"
	while [[ "$dir" != "/" && -n "$dir" ]]; do
		[[ -e "$dir/$2" ]] && { printf '%s\n' "$dir"; return 0; }
		dir=$(dirname -- "$dir")
	done
	return 1
}

# node_bin <start-dir> <tool> : print the path of a locally installed node tool, if any.
# Only local installs are used: hooks never download code (no npx).
node_bin() {
	local dir="$1"
	while [[ "$dir" != "/" && -n "$dir" ]]; do
		[[ -x "$dir/node_modules/.bin/$2" ]] && { printf '%s\n' "$dir/node_modules/.bin/$2"; return 0; }
		dir=$(dirname -- "$dir")
	done
	return 1
}
