#!/usr/bin/env bash
# Tests for hooks/scripts/*.sh. Run: bash tests/hooks.test.sh
# Each case feeds a hook the JSON Claude Code would send and checks its output.
set -u
ROOT=$(cd -- "$(dirname -- "$0")/.." && pwd)
H="$ROOT/hooks/scripts"
TMP=$(mktemp -d)
trap 'rm -rf -- "$TMP"' EXIT
pass=0 fail=0

check() { # check <name> <condition-exit-code> [details]
	if [[ "$2" == 0 ]]; then pass=$((pass + 1)); echo "ok   $1"; else fail=$((fail + 1)); echo "FAIL $1${3:+: $3}"; fi
}
run() { # run <script> <json> -> stdout
	printf '%s' "$2" | "$H/$1"
}
edit_json() { printf '{"tool_name":"Edit","tool_input":{"file_path":"%s"}}' "$1"; }

# --- protect-generated ------------------------------------------------------------
mkdir -p "$TMP/gen" "$TMP/mod/internal/x"
printf '// Code generated by sqlc. DO NOT EDIT.\n\npackage sqlcgen\n' >"$TMP/gen/q.go"
printf 'package x\n' >"$TMP/mod/internal/x/x.go"
printf '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n' >"$TMP/gen/schema.ts"

out=$(run protect-generated.sh "$(edit_json "$TMP/gen/q.go")")
grep -q '"permissionDecision":"deny"' <<<"$out"; check "protect: denies Go generated file" $? "$out"
out=$(run protect-generated.sh "$(edit_json "$TMP/gen/schema.ts")")
grep -q '"deny"' <<<"$out"; check "protect: denies openapi-typescript output" $? "$out"
out=$(run protect-generated.sh "$(edit_json "$TMP/mod/internal/x/x.go")")
[[ -z "$out" ]]; check "protect: allows hand-written file" $? "$out"
out=$(run protect-generated.sh "$(edit_json "$TMP/does/not/exist.go")")
[[ -z "$out" ]]; check "protect: allows a new file" $? "$out"

# --- post-edit: Go ------------------------------------------------------------------
if command -v go >/dev/null 2>&1; then
	printf 'module example.com/m\n\ngo 1.27\n' >"$TMP/mod/go.mod"
	printf 'package x\nfunc  F( )int{return 1}\n' >"$TMP/mod/internal/x/x.go"
	out=$(run post-edit.sh "$(edit_json "$TMP/mod/internal/x/x.go")")
	grep -q 'func F() int' "$TMP/mod/internal/x/x.go"; check "post-edit: formats Go" $? "$(cat "$TMP/mod/internal/x/x.go")"
	[[ -z "$out" ]]; check "post-edit: clean Go file is silent" $? "$out"

	printf 'package x\n\nfunc F() int {\n' >"$TMP/mod/internal/x/x.go"
	out=$(run post-edit.sh "$(edit_json "$TMP/mod/internal/x/x.go")")
	grep -q 'syntax error' <<<"$out"; check "post-edit: reports Go syntax error" $? "$out"

	printf 'package x\n\nimport "fmt"\n\nfunc F() { fmt.Printf("%%d\\n", "s") }\n' >"$TMP/mod/internal/x/x.go"
	out=$(run post-edit.sh "$(edit_json "$TMP/mod/internal/x/x.go")")
	grep -q 'go vet' <<<"$out"; check "post-edit: reports go vet findings" $? "$out"
	grep -q 'Debug output' <<<"$out"; check "post-edit: flags fmt.Printf in production code" $? "$out"

	printf 'package x\n\nimport "fmt"\n\nfunc G() { fmt.Println("x") }\n' >"$TMP/mod/internal/x/x_test.go"
	printf 'package x\n' >"$TMP/mod/internal/x/x.go"
	out=$(run post-edit.sh "$(edit_json "$TMP/mod/internal/x/x_test.go")")
	! grep -q 'Debug output' <<<"$out"; check "post-edit: allows prints in tests" $? "$out"

	out=$(ECC_GO_VET=0 run post-edit.sh "$(edit_json "$TMP/gen/q.go")")
	[[ -z "$out" ]]; check "post-edit: skips generated files" $? "$out"

	# goimports gets -local <module path>, so the module's imports group like golangci-lint wants.
	mkdir -p "$TMP/fakebin"
	printf '#!/usr/bin/env bash\nprintf "%%s\\n" "$@" >"%s/goimports.args"\n' "$TMP" >"$TMP/fakebin/goimports"
	chmod +x "$TMP/fakebin/goimports"
	printf 'package x\n' >"$TMP/mod/internal/x/x.go"
	PATH="$TMP/fakebin:$PATH" ECC_GO_VET=0 run post-edit.sh "$(edit_json "$TMP/mod/internal/x/x.go")" >/dev/null
	grep -qx -- '-local' "$TMP/goimports.args" && grep -qx 'example.com/m' "$TMP/goimports.args"
	check "post-edit: goimports -local <module path from go.mod>" $? "$(cat "$TMP/goimports.args" 2>/dev/null)"
else
	echo "skip Go cases: go not installed"
fi

# --- post-edit: TypeScript ---------------------------------------------------------
mkdir -p "$TMP/web/src"
printf '{"name":"web"}\n' >"$TMP/web/package.json"
printf 'export function f() { console.log("x"); return 1 }\n' >"$TMP/web/src/a.ts"
out=$(run post-edit.sh "$(edit_json "$TMP/web/src/a.ts")")
grep -q 'console.log' <<<"$out"; check "post-edit: flags console.log in web code" $? "$out"
printf 'test("x", () => { console.log("x") })\n' >"$TMP/web/src/a.test.ts"
out=$(run post-edit.sh "$(edit_json "$TMP/web/src/a.test.ts")")
[[ -z "$out" ]]; check "post-edit: allows console.log in tests" $? "$out"

# --- stop-check ----------------------------------------------------------------------
repo="$TMP/repo"
mkdir -p "$repo/backend/internal/x" "$repo/backend/cmd/app" "$repo/web/src"
git -C "$repo" init -q && git -C "$repo" -c user.email=t@t -c user.name=t commit -q --allow-empty -m init
printf 'package x\n\nfunc F() {}\n' >"$repo/backend/internal/x/x.go"
git -C "$repo" add -A && git -C "$repo" -c user.email=t@t -c user.name=t commit -q -m base
stop_json() { printf '{"cwd":"%s","stop_hook_active":%s}' "$repo" "$1"; }

out=$(run stop-check.sh "$(stop_json false)")
[[ -z "$out" ]]; check "stop: clean tree passes" $? "$out"

printf 'package x\n\nimport "fmt"\n\nfunc F() { fmt.Println("debug") }\n' >"$repo/backend/internal/x/x.go"
printf 'package main\n\nimport "fmt"\n\nfunc main() { fmt.Println("usage") }\n' >"$repo/backend/cmd/app/main.go"
git -C "$repo" add -A
out=$(run stop-check.sh "$(stop_json false)")
grep -q '"decision":"block"' <<<"$out" && grep -q 'internal/x/x.go:5' <<<"$out"; check "stop: blocks on added fmt.Println with file:line" $? "$out"
! grep -q 'cmd/app' <<<"$out"; check "stop: ignores cmd/" $? "$out"

out=$(run stop-check.sh "$(stop_json true)")
[[ -z "$out" ]]; check "stop: never loops when stop_hook_active" $? "$out"

# --- hooks.json is valid and points at executable scripts -------------------------------
python3 -I -c 'import json,sys; json.load(open(sys.argv[1]))' "$ROOT/hooks/hooks.json"; check "hooks.json is valid JSON" $?
for s in protect-generated post-edit stop-check; do [[ -x "$H/$s.sh" ]]; check "$s.sh is executable" $?; done

echo "--- $pass passed, $fail failed"
[[ $fail == 0 ]]
